export const NIGHT_SHIFT_SCRIPT = `NIGHT SHIFT
A short film

FADE IN:

EXT. DOWNTOWN GARAGE - NIGHT

Rain sheets off a neon PARKING sign. The structure is a concrete hive: six stories of ramps, sodium light, and wet tire-shine. A BLACK SEDAN turns in off the street and disappears up the first ramp.

INT. GARAGE BOOTH - NIGHT

MARA (30s), night attendant, sits behind bullet glass with a paperback and a thermos. A radio murmurs a late score. She does not look up until the sedan stops at the window.

The DRIVER does not look at her. Gloved hands. A watch that costs more than the booth.

DRIVER
Ticket.

She slides one through the tray. His fingers take it. The sedan glides into the dark without paying.

MARA
(into the empty booth)
You're welcome.

She marks a hash in a little notebook. Not a log. A tally.

INT. LEVEL FOUR - NIGHT

The sedan parks nose-in against a blank wall. The Driver kills the lights but not the engine. Rain ticks on the roof.

A SECOND FIGURE steps from behind a concrete column — COLE (40s), coat too thin for the weather. He carries a small envelope.

They do not shake hands. Cole slides the envelope through the passenger window. The Driver hands back a folded slip of paper.

COLE
That's the last.

The sedan pulls out. Cole stands in the empty bay and looks — not at the car — at the booth camera mounted high in the corner. The red light is on.

INT. GARAGE BOOTH - NIGHT

Mara watches the monitor. Grainy. Cole looking directly into the lens.

She turns the paperback face-down. The radio has gone to static.

A knock on the glass. Cole is there. Close. Rain on his shoulders.

COLE
You saw that.

MARA
I saw a man park badly.

COLE
Turn the camera off.

She does not. Her hand is on the thermos. Not a weapon. A weight.

MARA
Shift ends at five.

COLE
You won't make five.

He leaves a parking ticket in the tray — her own ticket, stamped, with a phone number written in pencil on the back. Then he is gone down the stairwell.

INT. STAIRWELL - NIGHT

Mara descends with a flashlight. Each landing smells like wet concrete and old oil. She stops at Level Four. The bay is empty except for a small envelope the rain has not reached, tucked against the base of the column.

She picks it up. Inside: a garage chip. Number 19. And a photograph of the booth. Of her. Taken from the sedan.

EXT. ROOFTOP LEVEL - NIGHT

Wind. The city laid out in wet grids. The black sedan is idling at the far wall, lights off.

Mara walks toward it with the envelope held out like a truce. The Driver's window lowers an inch.

DRIVER
You should have stayed in the booth.

MARA
You should have paid.

A beat. Something like a smile that is not a smile.

The sedan's reverse lights bloom. It rolls toward her — slow, then not. She steps aside at the last second. The car clips the parapet, sparks, and stops.

Silence except rain.

The Driver does not get out. Cole does — from the back seat, which was never empty.

COLE
Give me the chip.

MARA
Come into the light and ask.

He does not. She flicks the chip off the roof. It vanishes into six stories of dark.

INT. GARAGE BOOTH - PRE-DAWN

Mara sits behind the glass. Paperback open. Thermos empty. The radio has found a station again.

A new car rolls up. A woman with a commute face.

WOMAN
Ticket, please.

Mara slides one through. Her hand is steady. On the monitor, Level Four is empty. The rooftop camera shows only rain.

She adds a hash to the notebook. Then she closes it.

FADE OUT.
`;

